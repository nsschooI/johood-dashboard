// وحط الـ Client ID هنا، وأضف redirect: http://127.0.0.1:53712/callback
const DISCORD_CLIENT_ID = ''          // ← ضع Client ID هنا لتفعيل الربط
const DISCORD_CLIENT_SECRET = ''      // اختياري (الأفضل عبر باك-إند لاحقاً)
const DISCORD_PORT = 53712
const DISCORD_REDIRECT = `http://127.0.0.1:${DISCORD_PORT}/callback`

// ── Settings store (simple JSON) ──────────────────────────────────────────
const settingsPath = path.join(app.getPath('userData'), 'settings.json')

const defaultSettings = {
  eorEnabled:    true,
  resetEnabled:  false,
  selectEnabled: false,
  editKey:       'F',
  resetKey:      'G',
  selectKey:     'LButton',
  selectDelay:   45,
  ping:          30,
  macroOn:       false,
  theme:         'dark',
  launchOnBoot:  false,
  startMinimized:false,
  discord:       null
}

function loadSettings() {
  try {
    if (fs.existsSync(settingsPath)) {
      return { ...defaultSettings, ...JSON.parse(fs.readFileSync(settingsPath, 'utf8')) }
    }
  } catch {}
  return { ...defaultSettings }
}

function saveSettings(s) {
  try { fs.writeFileSync(settingsPath, JSON.stringify(s, null, 2)) } catch {}
}

// ── AHK generation ────────────────────────────────────────────────────────
function generateAHK(s) {
  const delay = Math.max(10, Math.round(s.ping * 0.25) + 15)
  const ek = s.editKey
  const rk = s.resetKey
  const sk = s.selectKey

  let script = `; ============================================
;  JoHood Macro v1.0 - فورت نايت
;  Generated by JoHood Macro App
; ============================================

#Requires AutoHotkey v2.0
#SingleInstance Force
SetWorkingDir(A_ScriptDir)
SetKeyDelay(-1, -1)

global MacroEnabled := true
global EditHeld     := false
global Delay        := ${delay}

; ─── يشتغل بس لما فورت نايت تكون النافذة النشطة ───
#HotIf WinActive("ahk_exe FortniteClient-Win64-Shipping.exe")

`

  if (s.eorEnabled) {
    script += `; ─── أديت عند الرفع ────────────────────────
*${ek}:: {
    global MacroEnabled, EditHeld
    if (EditHeld) {
        return  ; تجاهل التكرار التلقائي من الويندوز لما تضل كابس
    }
    if !MacroEnabled {
        Send("{Blind}{${ek} Down}")
        return
    }
    EditHeld := true
    Send("{Blind}{${ek} Down}")
`
    if (s.resetEnabled) {
      script += `    Sleep(10)
    Send("{Blind}{${rk}}")
    Sleep(10)
    Send("{Blind}{${ek}}")
`
    }
    if (s.selectEnabled) {
      script += `    Sleep(${Math.max(0, s.selectDelay ?? 45)})
    Send("{Blind}{${sk} Down}")
`
    }
    script += `}

*${ek} Up:: {
    global MacroEnabled, EditHeld, Delay
    Send("{Blind}{${ek} Up}")
    if (!MacroEnabled or !EditHeld) {
        EditHeld := false
        return
    }
    EditHeld := false
`
    if (s.selectEnabled) {
      script += `    Sleep(Delay)
    Send("{Blind}{${sk} Up}")  ; رفع زر السيليكت هو اللي بيعمل الكونفيرم تلقائياً
`
    } else {
      script += `    Sleep(Delay)
    Send("{Blind}{${sk}}")
`
    }
    script += `}

`
  }

  script += `; ─── F9: تشغيل / إيقاف ─────────────────────
F9:: {
    global MacroEnabled
    MacroEnabled := !MacroEnabled
    if MacroEnabled
        ToolTip("✅ JoHood ON")
    else
        ToolTip("❌ JoHood OFF")
    SetTimer(() => ToolTip(), -1500)
}

#HotIf
`
  return script
}

// ── AHK Process ───────────────────────────────────────────────────────────
let ahkProcess = null
let ahkPath    = null

function startMacro(settings) {
  stopMacro()
  const script = generateAHK(settings)
  ahkPath = path.join(app.getPath('temp'), 'johood_macro_active.ahk')
  fs.writeFileSync(ahkPath, script, 'utf8')

  // Try common AHK install locations
  const ahkLocations = [
    'C:\\Program Files\\AutoHotkey\\v2\\AutoHotkey64.exe',
    'C:\\Program Files\\AutoHotkey\\AutoHotkey.exe',
    'C:\\Program Files (x86)\\AutoHotkey\\AutoHotkey.exe',
    'AutoHotkey.exe'   // if in PATH
  ]

  let ahkExe = null
  for (const loc of ahkLocations) {
    if (loc === 'AutoHotkey.exe' || fs.existsSync(loc)) {
      ahkExe = loc
      break
    }
  }

  if (!ahkExe) {
    return { ok: false, error: 'AutoHotkey غير مثبّت. نزّله من autohotkey.com' }
  }

  ahkProcess = spawn(ahkExe, [ahkPath], { detached: false })
  ahkProcess.on('close', () => { ahkProcess = null })
  return { ok: true }
}

function stopMacro() {
  if (ahkProcess) {
    try { ahkProcess.kill() } catch {}
    ahkProcess = null
  }
  if (ahkPath && fs.existsSync(ahkPath)) {
    try { fs.unlinkSync(ahkPath) } catch {}
  }
}

// ── Window & App ──────────────────────────────────────────────────────────
let mainWindow = null
let tray       = null
let settings   = loadSettings()
let isQuitting = false

function createTrayIcon() {
  const icoPath = path.join(__dirname, '..', 'assets', 'icon.ico')
  let icon = nativeImage.createFromPath(icoPath)
  if (icon.isEmpty()) icon = nativeImage.createEmpty()
  tray = new Tray(icon)
  tray.setToolTip('JoHood Macro')
  updateTrayMenu()
  tray.on('double-click', showWindow)
}

function updateTrayMenu() {
  const macroRunning = !!ahkProcess
  const menu = Menu.buildFromTemplate([
    { label: 'JoHood Macro', enabled: false },
    { type: 'separator' },
    { label: macroRunning ? '🟢 الماكرو شغّال' : '🔴 الماكرو متوقف', enabled: false },
    { type: 'separator' },
    { label: '⚙️ الإعدادات', click: showWindow },
    { type: 'separator' },
    { label: '❌ إغلاق', click: () => { isQuitting = true; stopMacro(); app.quit() } }
  ])
  tray.setContextMenu(menu)
}

function showWindow() {
  if (mainWindow) {
    mainWindow.show()
    mainWindow.focus()
  }
}

function createWindow() {
  mainWindow = new BrowserWindow({
    width:  1000,
    height: 660,
    minWidth:  900,
    minHeight: 600,
    resizable: true,
    frame: false,          // custom title bar
    transparent: false,
    backgroundColor: settings.theme === 'light' ? '#eef0f6' : '#08080c',
    icon: path.join(__dirname, '..', 'assets', 'icon.ico'),
    webPreferences: {
      preload: path.join(__dirname, 'preload.js'),
      contextIsolation: true,
      nodeIntegration: false
    },
    show: false
  })

  mainWindow.loadFile(path.join(__dirname, 'index.html'))

  mainWindow.once('ready-to-show', () => {
    if (!settings.startMinimized) mainWindow.show()
    mainWindow.webContents.send('settings-loaded', { ...settings, version: APP_VERSION })
    mainWindow.webContents.send('macro-status', !!ahkProcess)
  })

  mainWindow.on('close', (e) => {
    if (isQuitting) return
    e.preventDefault()
    mainWindow.hide()
    // Show tray balloon on first minimize
  })

  if (process.env.NODE_ENV === 'development') {
    mainWindow.webContents.openDevTools({ mode: 'detach' })
  }
}

// ── Auto Update ───────────────────────────────────────────────────────────
function sendUpdateStatus(status, data) {
  mainWindow?.webContents.send('update-status', { status, ...data })
}

autoUpdater.on('checking-for-update', () => sendUpdateStatus('checking'))
