// ── Discord OAuth (loopback + PKCE) ─────────────────────────────────────────
function b64url(buf) {
  return buf.toString('base64').replace(/\+/g, '-').replace(/\//g, '_').replace(/=+$/, '')
}

function discordLogin() {
  return new Promise((resolve) => {
    if (!DISCORD_CLIENT_ID) { resolve({ ok: false, error: 'not-configured' }); return }

    const verifier  = b64url(crypto.randomBytes(32))
    const challenge = b64url(crypto.createHash('sha256').update(verifier).digest())
    const state     = b64url(crypto.randomBytes(16))
    let settled = false

    const server = http.createServer(async (req, res) => {
      try {
        const u = new URL(req.url, DISCORD_REDIRECT)
        if (u.pathname !== '/callback') { res.writeHead(404); res.end(); return }
        const code = u.searchParams.get('code')
        const retState = u.searchParams.get('state')
        res.writeHead(200, { 'Content-Type': 'text/html; charset=utf-8' })
        res.end('<!DOCTYPE html><html dir="rtl"><head><meta charset="utf-8"><title>JoHood</title></head><body style="margin:0;height:100vh;display:grid;place-items:center;font-family:Segoe UI,system-ui,sans-serif;color:#f5f5f7;background:radial-gradient(60vmax 60vmax at 20% 0%,rgba(255,55,95,.35),transparent 60%),radial-gradient(60vmax 60vmax at 100% 100%,rgba(94,92,230,.3),transparent 60%),#08080c"><div style="text-align:center;padding:36px 44px;border-radius:24px;background:rgba(28,28,36,.55);backdrop-filter:blur(30px);border:1px solid rgba(255,255,255,.1)"><div style="font-size:44px">✅</div><h2 style="margin:10px 0 6px;font-weight:600">تم ربط ديسكورد</h2><p style="margin:0;color:rgba(235,235,245,.62)">ارجع للتطبيق، تقدر تسكّر هالصفحة.</p></div></body></html>')
        server.close()
        if (settled) return
        settled = true
        if (!code || retState !== state) { resolve({ ok: false, error: 'bad-callback' }); return }

        const body = new URLSearchParams({
          client_id: DISCORD_CLIENT_ID,
          grant_type: 'authorization_code',
          code,
          redirect_uri: DISCORD_REDIRECT,
          code_verifier: verifier
        })
        if (DISCORD_CLIENT_SECRET) body.set('client_secret', DISCORD_CLIENT_SECRET)

        const tokenRes = await fetch('https://discord.com/api/oauth2/token', {
          method: 'POST',
          headers: { 'Content-Type': 'application/x-www-form-urlencoded' },
          body: body.toString()
        })
        const token = await tokenRes.json()
        if (!token.access_token) { resolve({ ok: false, error: 'token-failed' }); return }

        const meRes = await fetch('https://discord.com/api/users/@me', {
          headers: { Authorization: `Bearer ${token.access_token}` }
        })
        const me = await meRes.json()
        const user = {
          id: me.id, username: me.username,
          globalName: me.global_name, avatar: me.avatar
        }
        settings.discord = user
        saveSettings(settings)
        resolve({ ok: true, user })
      } catch (err) {
        if (!settled) { settled = true; resolve({ ok: false, error: String(err) }) }
      }
    })

    server.listen(DISCORD_PORT, '127.0.0.1', () => {
      const authUrl = 'https://discord.com/oauth2/authorize?' + new URLSearchParams({
        client_id: DISCORD_CLIENT_ID,
        response_type: 'code',
        redirect_uri: DISCORD_REDIRECT,
        scope: 'identify',
        state,
        code_challenge: challenge,
        code_challenge_method: 'S256'
      }).toString()
      shell.openExternal(authUrl)
    })

    setTimeout(() => { if (!settled) { settled = true; try { server.close() } catch {} resolve({ ok: false, error: 'timeout' }) } }, 180000)
  })
}

// ── Auto-launch on Windows boot ─────────────────────────────────────────────
function applyAutoLaunch(enabled) {
  try {
    app.setLoginItemSettings({ openAtLogin: !!enabled, args: ['--hidden'] })
  } catch {}
}

// ── IPC Handlers ──────────────────────────────────────────────────────────
ipcMain.handle('get-settings', () => ({ ...settings, version: APP_VERSION }))

ipcMain.handle('discord-login', () => discordLogin())
ipcMain.handle('discord-logout', () => { settings.discord = null; saveSettings(settings); return { ok: true } })
ipcMain.handle('set-auto-launch', (_, enabled) => { applyAutoLaunch(enabled); return { ok: true } })

ipcMain.handle('save-settings', (_, newSettings) => {
  settings = { ...settings, ...newSettings }
  saveSettings(settings)
  return { ok: true }
})

ipcMain.handle('start-macro', (_, s) => {
  settings = { ...settings, ...s }
  saveSettings(settings)
  const result = startMacro(settings)
  updateTrayMenu()
  return result
})

ipcMain.handle('stop-macro', () => {
  stopMacro()
  updateTrayMenu()
  return { ok: true }
})

ipcMain.handle('macro-status', () => ({ running: !!ahkProcess }))

ipcMain.handle('open-ahk-site', () => {
  shell.openExternal('https://www.autohotkey.com/')
  return {}
})

ipcMain.handle('check-for-updates', async () => {
  try {
    await autoUpdater.checkForUpdates()
    return { ok: true }
  } catch (err) {
    return { ok: false, error: err?.message || String(err) }
  }
})

ipcMain.handle('download-update', async () => {
  try {
    await autoUpdater.downloadUpdate()
    return { ok: true }
  } catch (err) {
    return { ok: false, error: err?.message || String(err) }
  }
})

ipcMain.handle('install-update', () => {
  autoUpdater.quitAndInstall()
  return {}
})

ipcMain.on('window-minimize', () => mainWindow?.minimize())
ipcMain.on('window-close',    () => mainWindow?.hide())

// ── App lifecycle ─────────────────────────────────────────────────────────
app.whenReady().then(() => {
  // لو انفتح من بدء تشغيل الويندوز بوسم --hidden، يبدأ مصغّر بالـ Tray
  if (process.argv.includes('--hidden')) settings.startMinimized = true
  applyAutoLaunch(settings.launchOnBoot)

  createWindow()
  createTrayIcon()

  setTimeout(() => autoUpdater.checkForUpdates().catch(() => {}), 3000)

  app.on('activate', () => {
    if (BrowserWindow.getAllWindows().length === 0) createWindow()
  })
})

app.on('window-all-closed', () => {
  // Keep running in tray on Windows
  if (process.platform !== 'darwin') return
  app.quit()
})

app.on('before-quit', () => {
  isQuitting = true
  stopMacro()
})
